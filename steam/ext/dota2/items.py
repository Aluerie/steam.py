    @classmethod
    def from_internal_name(cls: type[Self], value: str) -> Item:
        """Get the item by its internal name, e.g. ``"item_blink"``."""
        return next(item for item, internal_name in cls.INTERNAL_NAMES.items() if internal_name == value)

    @property
    def display_name(self) -> str:
        """Item Display Name.

        These should match how the item is named in the game client.
        """
        return self.DISPLAY_NAMES[self]

    @property
    def internal_name(self) -> str:
        """Item Internal Name, e.g. ``"item_blink"``.

        These names are often used in various API, including Valve and 3rd parties.
        """
        return self.INTERNAL_NAMES[self]

    @property
    def id(self) -> int:
        return self.value

    def __bool__(self) -> bool:  # type: ignore # `Item.NONE` should be returning `False`
        return bool(self.value)
