"""
A script to generate the Dota 2 ``Item`` enum module from Valve's datafeed item list.

The whole ``steam/ext/dota2/enums/items.py`` module is generated by this script.
New items get a member name derived from their English name, or from their internal name when the English name
is empty or shared by several items (e.g. Dagon levels). Existing member names are never changed.
Display names and internal names of existing items are refreshed from the datafeed.
Items missing from the datafeed are kept as they are, old matches can still have them.

Prints a short summary of the changes as Markdown (empty when nothing changed).

Licensed under The MIT License (MIT) - Copyright (c) 2020-present James H-B. See LICENSE
"""

from __future__ import annotations

import json
import re
import sys
import urllib.request
from collections import Counter
from pathlib import Path
from typing import Final, NamedTuple

ROOT: Final = Path(__file__).parent
ITEMS_FILE: Final = ROOT.parent / "steam" / "ext" / "dota2" / "enums" / "items.py"
ITEM_LIST_URL: Final = "https://www.dota2.com/datafeed/itemlist?language=english"

MEMBER_RE: Final = re.compile(r"^    (\w+) = (\d+)$")
DISPLAY_RE: Final = re.compile(r'^            cls\.(\w+): (".*"),$')
INTERNAL_RE: Final = re.compile(r'^            cls\.(\w+): "(item_\w+)",$')

TEMPLATE: Final = '''\
"""Licensed under The MIT License (MIT) - Copyright (c) 2020-present James H-B. See LICENSE

Generated by ``scripts/update_dota2_items.py`` from Valve's datafeed, don't edit it by hand.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

from ....enums import IntEnum, classproperty

if TYPE_CHECKING:
    from collections.abc import Mapping
    from typing import Self

__all__ = ("Item",)


class Item(IntEnum):
    """Enum representing Dota 2 Item.

    Primarily, mapping item_id to item name. Includes recipes and neutral items.
    """

    NONE = 0
{members}

    @classproperty
    def DISPLAY_NAMES(cls: type[Self]) -> Mapping[Item, str]:  # type: ignore
        return {{
{display_names}
        }}

    @classproperty
    def INTERNAL_NAMES(cls: type[Self]) -> Mapping[Item, str]:  # type: ignore
        return {{
{internal_names}
        }}

    @classmethod
    def from_internal_name(cls: type[Self], value: str) -> Item:
        """Get the item by its internal name, e.g. ``"item_blink"``."""
        return next(item for item, internal_name in cls.INTERNAL_NAMES.items() if internal_name == value)

    @property
    def display_name(self) -> str:
        """Item Display Name.

        These should match how the item is named in the game client.
        """
        return self.DISPLAY_NAMES[self]

    @property
    def internal_name(self) -> str:
        """Item Internal Name, e.g. ``"item_blink"``.

        These names are often used in various API, including Valve and 3rd parties.
        """
        return self.INTERNAL_NAMES[self]

    @property
    def id(self) -> int:
        return self.value

    def __bool__(self) -> bool:  # type: ignore # `Item.NONE` should be returning `False`
        return bool(self.value)
'''


class ItemInfo(NamedTuple):
    member: str
    display_name: str
    internal_name: str


def fetch_items() -> dict[int, tuple[str, str]]:
    """Return ``{item_id: (english_name, internal_name)}`` from the datafeed."""
    request = urllib.request.Request(ITEM_LIST_URL, headers={"User-Agent": "steam.py item updater"})
    with urllib.request.urlopen(request, timeout=60) as response:
        data = json.load(response)
    items = data["result"]["data"]["itemabilities"]
    if not items:
        raise RuntimeError("Datafeed returned an empty item list")
    # a few names have line breaks in them, e.g. "Black Grimoire\n(Warlock)"
    return {item["id"]: (" ".join(item["name_english_loc"].split()), item["name"]) for item in items}


def camel_case(text: str) -> str:
    """Turn ``"Eul's Scepter of Divinity"`` into ``"EulsScepterOfDivinity"``."""
    words = re.split(r"[^0-9A-Za-z]+", text.replace("'", ""))
    name = "".join(word[:1].upper() + word[1:] for word in words if word)
    if not name.isidentifier():
        raise ValueError(f"Can't make an enum member name out of {text!r}")
    return name


def recipe_target(internal_name: str) -> str | None:
    """Return the internal name of the item a recipe makes, ``None`` if it isn't a recipe."""
    if internal_name.startswith("item_recipe_"):
        return f"item_{internal_name.removeprefix('item_recipe_')}"
    return None


def fallback_display_name(internal_name: str, english_names: dict[str, str]) -> str:
    """Make a display name for an item the datafeed has no English name for, e.g. most recipes."""
    target = recipe_target(internal_name)
    if target and (target_name := english_names.get(target)):
        return f"{target_name} Recipe"  # same style as the recipes that do have an English name
    return internal_name.removeprefix("item_").replace("_", " ").title()


def read_existing() -> dict[int, ItemInfo]:
    """Parse the currently generated module, empty if there is none yet."""
    try:
        lines = ITEMS_FILE.read_bytes().decode().split("\n")
    except FileNotFoundError:
        return {}
    # the display and internal name blocks look alike, so each is parsed from its own part of the file
    split = next(i for i, line in enumerate(lines) if "def INTERNAL_NAMES" in line)
    members = {int(m[2]): m[1] for m in map(MEMBER_RE.match, lines[:split]) if m}
    display_names = {m[1]: json.loads(m[2]) for m in map(DISPLAY_RE.match, lines[:split]) if m}
    internal_names = {m[1]: m[2] for m in map(INTERNAL_RE.match, lines[split:]) if m}
    return {
        item_id: ItemInfo(member, display_names[member], internal_names[member])
        for item_id, member in members.items()
        if item_id != 0
    }


def render(items: dict[int, ItemInfo]) -> str:
    """Make the module source for these items."""
    ordered = sorted(items.items())
    return TEMPLATE.format(
        members="\n".join(f"    {info.member} = {item_id}" for item_id, info in ordered),
        display_names="\n".join(
            [
                '            cls.NONE: "Empty",',
                *(
                    f"            cls.{info.member}: {json.dumps(info.display_name, ensure_ascii=False)},"
                    for _, info in ordered
                ),
            ]
        ),
        internal_names="\n".join(f'            cls.{info.member}: "{info.internal_name}",' for _, info in ordered),
    )


def main() -> None:
    items = read_existing()
    created = not items
    feed = fetch_items()

    english_by_internal = {internal: english for english, internal in feed.values()}
    english_member_counts = Counter(camel_case(english) for english, _ in feed.values() if english)

    def new_member(english_name: str, internal_name: str) -> str:
        if target := recipe_target(internal_name):
            # "Recipe" + the member of the item it makes, e.g. RecipeAghanimsScepter
            target_info = next((info for info in items.values() if info.internal_name == target), None)
            return "Recipe" + (target_info.member if target_info else camel_case(target.removeprefix("item_")))
        if english_name and english_member_counts[camel_case(english_name)] == 1:
            return camel_case(english_name)
        # no English name, or one shared by several items, e.g. Dagon levels
        return camel_case(internal_name.removeprefix("item_"))

    changes: list[str] = []
    # recipes last, so the items they make already have their member names
    for item_id, (english_name, internal_name) in sorted(
        feed.items(), key=lambda kv: (recipe_target(kv[1][1]) is not None, kv[0])
    ):
        display_name = english_name or fallback_display_name(internal_name, english_by_internal)
        old = items.get(item_id)
        if old is None:
            member = new_member(english_name, internal_name)
            if any(info.member == member for info in items.values()):
                raise ValueError(f"Member name {member!r} for item {item_id} is already taken")
            new = ItemInfo(member, display_name, internal_name)
            changes.append(f"- Added `Item.{member} = {item_id}` ({display_name}, `{internal_name}`)")
        else:
            new = old._replace(display_name=display_name, internal_name=internal_name)
            if old.display_name != new.display_name:
                changes.append(f"- `Item.{old.member}` display name: {old.display_name!r} -> {new.display_name!r}")
            if old.internal_name != new.internal_name:
                changes.append(f"- `Item.{old.member}` internal name: `{old.internal_name}` -> `{new.internal_name}`")
        items[item_id] = new

    if not changes:
        return

    source = render(items)
    compile(source, str(ITEMS_FILE), "exec")
    ITEMS_FILE.write_bytes(source.encode())
    if created:
        sys.stdout.write(f"- Generated `Item` with {len(items)} items\n")
    else:
        sys.stdout.write("\n".join(changes) + "\n")


if __name__ == "__main__":
    main()
