"""
A script to generate the Dota 2 ``Hero`` enum module from Valve's datafeed hero list.

The whole ``steam/ext/dota2/enums/heroes.py`` module is generated by this script.
New heroes get a member name derived from their English name; existing member names are never changed.
Display names and NPC names of existing heroes are refreshed from the datafeed.
Heroes missing from the datafeed are kept as they are.

Prints a short summary of the changes as Markdown (empty when nothing changed).

Licensed under The MIT License (MIT) - Copyright (c) 2020-present James H-B. See LICENSE
"""

from __future__ import annotations

import json
import re
import sys
import urllib.request
from pathlib import Path
from typing import Final, NamedTuple

ROOT: Final = Path(__file__).parent
HEROES_FILE: Final = ROOT.parent / "steam" / "ext" / "dota2" / "enums" / "heroes.py"
HERO_LIST_URL: Final = "https://www.dota2.com/datafeed/herolist?language=english"

MEMBER_RE: Final = re.compile(r"^    (\w+) = (\d+)$")
DISPLAY_RE: Final = re.compile(r'^            cls\.(\w+): (".*"),$')
NPC_RE: Final = re.compile(r'^            cls\.(\w+): "(npc_dota_hero_\w+)",$')

TEMPLATE: Final = '''\
"""Licensed under The MIT License (MIT) - Copyright (c) 2020-present James H-B. See LICENSE

Generated by ``scripts/update_dota2_heroes.py`` from Valve's datafeed, don't edit it by hand.
"""

from __future__ import annotations

from typing import TYPE_CHECKING

from ....enums import IntEnum, classproperty

if TYPE_CHECKING:
    from collections.abc import Mapping
    from typing import Self

__all__ = ("Hero",)


class Hero(IntEnum):
    """Enum representing Dota 2 Hero.

    Primarily, mapping hero_id to hero name.
    """

    NONE = 0
{members}

    @classproperty
    def DISPLAY_NAMES(cls: type[Self]) -> Mapping[Hero, str]:  # type: ignore
        return {{
            cls.NONE: "None",  # happens when player disconnects or hasn't picked yet.
{display_names}
        }}

    @property
    def display_name(self) -> str:
        """Hero Display Name.

        These should match how the hero is named in the game client.
        """
        return self.DISPLAY_NAMES[self]

    @property
    def id(self) -> int:
        return self.value

    def __bool__(self) -> bool:  # type: ignore # `Hero.NONE` should be returning `False`
        return bool(self.value)

    @classproperty
    def NPC_NAMES(cls: type[Self]) -> Mapping[Hero, str]:  # type: ignore
        return {{
{npc_names}
        }}

    @classmethod
    def create_from_npc_dota_hero_name(cls: type[Self], value: str) -> Hero:
        return next(hero for hero, npc_name in cls.NPC_NAMES.items() if npc_name == value)

    @property
    def npc_name(self) -> str:
        """Hero NCP Name.

        These names are often used in various API, including Valve and 3rd parties.
        """
        return self.NPC_NAMES[self]

    @property
    def slug_name(self) -> str:
        """Hero Slug Name.

        Just like NPC names - these names are often used in API, including Valve and 3rd parties.
        Slug names are made by removing `"npc_dota_hero"` prefix from a hero's NPC name.
        """
        return self.NPC_NAMES[self].removeprefix("npc_dota_hero_")
'''


class HeroInfo(NamedTuple):
    member: str
    display_name: str
    npc_name: str


def fetch_heroes() -> dict[int, tuple[str, str]]:
    """Return ``{hero_id: (english_name, npc_name)}`` from the datafeed."""
    request = urllib.request.Request(HERO_LIST_URL, headers={"User-Agent": "steam.py hero updater"})
    with urllib.request.urlopen(request, timeout=30) as response:
        data = json.load(response)
    heroes = data["result"]["data"]["heroes"]
    if not heroes:
        raise RuntimeError("Datafeed returned an empty hero list")
    return {hero["id"]: (hero["name_english_loc"], hero["name"]) for hero in heroes}


def member_name(display_name: str) -> str:
    """Turn ``"Keeper of the Light"`` into ``"KeeperOfTheLight"``."""
    words = re.split(r"[^0-9A-Za-z]+", display_name.replace("'", ""))
    name = "".join(word[:1].upper() + word[1:] for word in words if word)
    if not name.isidentifier():
        raise ValueError(f"Can't make an enum member name out of {display_name!r}")
    return name


def read_existing() -> dict[int, HeroInfo]:
    """Parse the currently generated module."""
    lines = HEROES_FILE.read_bytes().decode().split("\n")
    # the display and NPC name blocks look alike, so each is parsed from its own part of the file
    split = next(i for i, line in enumerate(lines) if "def NPC_NAMES" in line)
    members = {int(m[2]): m[1] for m in map(MEMBER_RE.match, lines[:split]) if m}
    display_names = {m[1]: json.loads(m[2]) for m in map(DISPLAY_RE.match, lines[:split]) if m}
    npc_names = {m[1]: m[2] for m in map(NPC_RE.match, lines[split:]) if m}
    return {
        hero_id: HeroInfo(member, display_names[member], npc_names[member])
        for hero_id, member in members.items()
        if hero_id != 0
    }


def render(heroes: dict[int, HeroInfo]) -> str:
    """Make the module source for these heroes."""
    ordered = sorted(heroes.items())
    return TEMPLATE.format(
        members="\n".join(f"    {info.member} = {hero_id}" for hero_id, info in ordered),
        display_names="\n".join(
            f"            cls.{info.member}: {json.dumps(info.display_name, ensure_ascii=False)},"
            for _, info in ordered
        ),
        npc_names="\n".join(f'            cls.{info.member}: "{info.npc_name}",' for _, info in ordered),
    )


def main() -> None:
    heroes = read_existing()

    changes: list[str] = []
    for hero_id, (english_name, npc_name) in sorted(fetch_heroes().items()):
        old = heroes.get(hero_id)
        if old is None:
            new = HeroInfo(member_name(english_name), english_name, npc_name)
            if any(info.member == new.member for info in heroes.values()):
                raise ValueError(f"Member name {new.member!r} for hero {hero_id} is already taken")
            changes.append(f"- Added `Hero.{new.member} = {hero_id}` ({english_name}, `{npc_name}`)")
        else:
            new = old._replace(display_name=english_name, npc_name=npc_name)
            if old.display_name != new.display_name:
                changes.append(f"- `Hero.{old.member}` display name: {old.display_name!r} -> {new.display_name!r}")
            if old.npc_name != new.npc_name:
                changes.append(f"- `Hero.{old.member}` NPC name: `{old.npc_name}` -> `{new.npc_name}`")
        heroes[hero_id] = new

    if not changes:
        return

    source = render(heroes)
    compile(source, str(HEROES_FILE), "exec")
    HEROES_FILE.write_bytes(source.encode())
    sys.stdout.write("\n".join(changes) + "\n")


if __name__ == "__main__":
    main()
